"""Prepare the Blender weather renders (art/blender/weather/render_weather_fx.py) for Roblox.

  python3 tools/weather_sprites.py RENDER_OUT_DIR && python3 tools/upload_textures.py

- clouds/<Name>.png: cropped to the cloud (+ a small margin), at most 1024 px on the long side
  -> art/weather/clouds/Cloud_<Name>.png, and src/shared/CloudSprites.luau gets each one's
  aspect and kind (cumulus "Cu"/"Cg", stratus "St")
- fx/*.png (Splash and Ripple flipbooks 4x4, RainDrop, Spray) -> art/weather/tex/
Every file is added to art/weather/textures.json so upload_textures.py uploads it into
TextureIds.Weather.
"""
import json
import os
import shutil
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def main():
    src = sys.argv[1]
    tex_json = os.path.join(ROOT, "art", "weather", "textures.json")
    m = json.load(open(tex_json))
    cdir = os.path.join(ROOT, "art", "weather", "clouds")
    os.makedirs(cdir, exist_ok=True)
    sprites = []
    for fn in sorted(os.listdir(os.path.join(src, "clouds"))):
        if not fn.endswith(".png"):
            continue
        name = fn[:-4]
        im = Image.open(os.path.join(src, "clouds", fn)).convert("RGBA")
        a = im.getchannel("A").point(lambda v: 255 if v > 6 else 0)
        box = a.getbbox()
        if not box:
            print("empty render:", fn)
            continue
        pad = int(max(box[2] - box[0], box[3] - box[1]) * 0.03) + 2
        box = (max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad))
        im = im.crop(box)
        k = min(1.0, 1024 / max(im.size))
        if k < 1:
            im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
        out = os.path.join(cdir, f"Cloud_{name}.png")
        im.save(out)
        m[f"Cloud_{name}"] = os.path.relpath(out, ROOT)
        sprites.append((name, im.width, im.height))
        print(out, im.size)
    for fn, key in (("Splash.png", "SplashFlip"), ("Ripple.png", "RippleFlip"), ("RainDrop.png", "RainDrop"), ("Spray.png", "Spray")):
        p = os.path.join(src, "fx", fn)
        if os.path.exists(p):
            out = os.path.join(ROOT, "art", "weather", "tex", key + ".png")
            shutil.copy(p, out)
            m[key] = os.path.relpath(out, ROOT)
            print(out)
    json.dump(m, open(tex_json, "w"), indent=1)
    lines = ["-- Generated by tools/weather_sprites.py: rendered cloud sprites (TextureIds.Weather.Cloud_<Name>).",
             "-- kind: Cu = cumulus, Cg = towering cumulus, St = stratus bank. aspect = width / height.", "return {"]
    for name, w, h in sprites:
        lines.append(f'\t{{ name = "{name}", kind = "{name[:2]}", aspect = {w / h:.3f} }},')
    open(os.path.join(ROOT, "src", "shared", "CloudSprites.luau"), "w").write("\n".join(lines + ["}", ""]))


if __name__ == "__main__":
    main()
