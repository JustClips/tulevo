"""Upload model colour textures (and art/weather/textures.json) as Roblox Images and write src/shared/TextureIds.luau.

  python3 tools/upload_textures.py

For every art/models/<Model>/textures.json ({ part name: png path }), each png is uploaded once
(sha cache in art/textures.lock.json) and checked for moderation. Server/CityBuildings sets
MeshPart.TextureID from these ids, so buildings keep their textures even when the GLB's
embedded SurfaceAppearance images fail to show in game.
"""
import hashlib
import json
import os
import sys
import time
import uuid

sys.path.insert(0, os.path.dirname(__file__))
from upload_anims import CREATOR, GRANTS, request  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
LOCK = os.path.join(ROOT, "art", "textures.lock.json")
LUA = os.path.join(ROOT, "src", "shared", "TextureIds.luau")


def upload(path):
    name = os.path.splitext(os.path.basename(path))[0]
    meta = {"assetType": "Image", "displayName": f"Tulevo {name}"[:50], "description": "Tulevo texture",
            "creationContext": {"creator": {"userId": CREATOR}}}
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n"
            f"{json.dumps(meta)}\r\n--{b}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{os.path.basename(path)}\"\r\nContent-Type: image/png\r\n\r\n").encode() + open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    code, op = request("POST", "https://apis.roblox.com/assets/v1/assets", body, {"Content-Type": f"multipart/form-data; boundary={b}"})
    if code >= 300:
        raise RuntimeError(f"upload {name} failed: {code} {op}")
    for _ in range(90):
        if op.get("done"):
            break
        time.sleep(2)
        code, op = request("GET", f"https://apis.roblox.com/assets/v1/{op['path']}")
    asset_id = int((op.get("response") or {})["assetId"])
    # a fresh asset often answers CannotManageAsset for a while; without the grant Dev's alt / the
    # group game can't load the image and the building shows grey, so retry until it sticks
    for subject, sid in GRANTS:
        for _ in range(12):
            body = {"subjectType": subject, "subjectId": sid, "action": "Use", "requests": [{"assetId": asset_id, "grantToDependencies": False}]}
            code, r = request("PATCH", "https://apis.roblox.com/asset-permissions-api/v1/assets/permissions",
                              json.dumps(body).encode(), {"Content-Type": "application/json-patch+json"})
            errs = (r.get("errors") if isinstance(r, dict) else None) or []
            if code < 300 and not errs:
                break
            time.sleep(10)
        else:
            print(f"  grant {subject} {sid} failed for {asset_id}: {code} {errs or r}")
    return asset_id


def moderation(asset_id):
    code, r = request("GET", f"https://apis.roblox.com/assets/v1/assets/{asset_id}?readMask=moderationResult")
    return ((r or {}).get("moderationResult") or {}).get("moderationState", "?")


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    models = {}
    base = os.path.join(ROOT, "art", "models")
    sources = [(m, os.path.join(base, m, "textures.json")) for m in sorted(os.listdir(base))]
    sources.append(("Weather", os.path.join(ROOT, "art", "weather", "textures.json")))  # rain + sky
    for model, mp in sources:
        if not os.path.exists(mp):
            continue
        parts = json.load(open(mp))
        ids = {}
        for part, rel in sorted(parts.items()):
            path = os.path.join(ROOT, rel)
            h = hashlib.sha256(open(path, "rb").read()).hexdigest()
            if h not in lock:
                lock[h] = {"id": upload(path), "file": rel}
                print(f"uploaded {rel} = {lock[h]['id']}")
                json.dump(lock, open(LOCK, "w"), indent=1)
            ids[part] = lock[h]["id"]
        models[model] = ids
    for h, v in lock.items():
        if v.get("state") != "Approved":
            v["state"] = moderation(v["id"])
            if v["state"] != "Approved":
                print(f"  {v['file']} ({v['id']}): {v['state']}")
    json.dump(lock, open(LOCK, "w"), indent=1)
    lines = ["-- Generated by tools/upload_textures.py: Roblox Image ids per building part.", "return {"]
    for model, ids in models.items():
        lines.append(f"\t{model} = {{")
        lines += [f"\t\t{p} = {i}," for p, i in ids.items()]
        lines.append("\t},")
    open(LUA, "w").write("\n".join(lines + ["}", ""]))


if __name__ == "__main__":
    main()
