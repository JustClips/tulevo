"""Upload art/models/<Name>/<Name>.glb to Roblox as Models and write src/shared/ModelIds.luau.

  python3 tools/upload_models.py [--force]

Needs env ROBLOXAPIKEY (never printed). Unchanged files are skipped (hash cache in
art/models.lock.json). New uploads are granted Use to Dev's alt and group, like animations.
GLB: 1 m = 1 stud, Blender -Y forward = Roblox -Z, Blender Z up = Roblox Y up.
"""
import hashlib
import json
import os
import sys
import time
import uuid

sys.path.insert(0, os.path.dirname(__file__))
from upload_anims import CREATOR, GRANTS, request  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "art", "models")
LOCK = os.path.join(ROOT, "art", "models.lock.json")
LUA = os.path.join(ROOT, "src", "shared", "ModelIds.luau")


def upload(path, name):
    meta = {"assetType": "Model", "displayName": f"Tulevo {name}"[:50], "description": f"Tulevo: {name}",
            "creationContext": {"creator": {"userId": CREATOR}}}
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n"
            f"{json.dumps(meta)}\r\n--{b}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{os.path.basename(path)}\"\r\nContent-Type: model/gltf-binary\r\n\r\n").encode() + open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    code, op = request("POST", "https://apis.roblox.com/assets/v1/assets", body, {"Content-Type": f"multipart/form-data; boundary={b}"})
    if code >= 300:
        raise RuntimeError(f"upload {name} failed: {code} {op}")
    for _ in range(150):
        if op.get("done"):
            break
        time.sleep(2)
        code, op = request("GET", f"https://apis.roblox.com/assets/v1/{op['path']}")
    if not op.get("done"):
        raise RuntimeError(f"upload {name} timed out: {op}")
    asset_id = int((op.get("response") or {})["assetId"])
    for subject, sid in GRANTS:
        for _ in range(6):
            body = {"subjectType": subject, "subjectId": sid, "action": "Use", "requests": [{"assetId": asset_id, "grantToDependencies": False}]}
            code, r = request("PATCH", "https://apis.roblox.com/asset-permissions-api/v1/assets/permissions",
                              json.dumps(body).encode(), {"Content-Type": "application/json-patch+json"})
            errs = (r.get("errors") if isinstance(r, dict) else None) or []
            if code < 300 and not errs:
                break
            print(f"  grant {subject} {sid}: {code} {errs or r}")
            time.sleep(10)
    return asset_id


sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import strip_glb_textures  # noqa: E402


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    for name in sorted(os.listdir(SRC)):
        path = os.path.join(SRC, name, f"{name}.glb")
        if not os.path.exists(path):
            continue
        meta_p = os.path.join(SRC, name, "meta.json")
        if os.path.exists(meta_p) and "lamps" in json.load(open(meta_p)):   # art/blender/kit.py city buildings
            # textured via separate Images (LiveSyncTextures): drop the GLB's own images so Roblox
            # makes no SurfaceAppearances / TexturePacks (see tools/strip_glb_textures.py)
            strip_glb_textures.strip(path)
        h = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if lock.get(name, {}).get("sha") == h and "--force" not in sys.argv:
            continue
        print(f"uploading {name} ...")
        lock[name] = {"id": upload(path, name), "sha": h}
        print(f"  {name} = {lock[name]['id']}")
        json.dump(lock, open(LOCK, "w"), indent=1)
    lines = ["-- Generated by tools/upload_models.py. Roblox Model asset ids for art/models/*.", "return {"]
    lines += [f"\t{n} = {v['id']}," for n, v in sorted(lock.items())]
    open(LUA, "w").write("\n".join(lines + ["}", ""]))


if __name__ == "__main__":
    main()
