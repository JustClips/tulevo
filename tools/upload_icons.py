"""Upload art/icons/out/*.png to Roblox as Images and write src/shared/IconIds.luau.

  python3 tools/upload_icons.py [--force]

Needs env ROBLOXAPIKEY (never printed). Unchanged files are skipped (hash cache in
art/icons.lock.json). The icons themselves come from art/icons/gen.py (ForgeGUI) + proc.py.
"""
import hashlib
import json
import os
import sys
import time
import uuid

sys.path.insert(0, os.path.dirname(__file__))
from upload_anims import CREATOR, request  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "art", "icons", "out")
LOCK = os.path.join(ROOT, "art", "icons.lock.json")
LUA = os.path.join(ROOT, "src", "shared", "IconIds.luau")


def upload(path, name):
    meta = {"assetType": "Image", "displayName": f"Tulevo icon {name}"[:50], "description": f"Tulevo UI icon: {name}",
            "creationContext": {"creator": {"userId": CREATOR}}}
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n"
            f"{json.dumps(meta)}\r\n--{b}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{os.path.basename(path)}\"\r\nContent-Type: image/png\r\n\r\n").encode() + open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    code, op = request("POST", "https://apis.roblox.com/assets/v1/assets", body, {"Content-Type": f"multipart/form-data; boundary={b}"})
    if code >= 300:
        raise RuntimeError(f"upload {name} failed: {code} {op}")
    for _ in range(150):
        if op.get("done"):
            break
        time.sleep(2)
        code, op = request("GET", f"https://apis.roblox.com/assets/v1/{op['path']}")
    if not op.get("done"):
        raise RuntimeError(f"upload {name} timed out: {op}")
    asset_id = int((op.get("response") or {})["assetId"])
    body = {"subjectType": "All", "action": "Use", "requests": [{"assetId": asset_id, "grantToDependencies": False}]}
    code, r = request("PATCH", "https://apis.roblox.com/asset-permissions-api/v1/assets/permissions",
                      json.dumps(body).encode(), {"Content-Type": "application/json-patch+json"})
    if code >= 300:
        print(f"  grant All for {name}: {code} {r}")
    return asset_id


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    for f in sorted(os.listdir(SRC)):
        if not f.endswith(".png"):
            continue
        name = f[:-4]
        path = os.path.join(SRC, f)
        h = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if lock.get(name, {}).get("sha") == h and "--force" not in sys.argv:
            continue
        print(f"uploading {name} ...")
        lock[name] = {"id": upload(path, name), "sha": h}
        print(f"  {name} = {lock[name]['id']}")
        json.dump(lock, open(LOCK, "w"), indent=1)
    lines = ["-- Generated by tools/upload_icons.py. Roblox Image asset ids for art/icons/out/*.png.", "return {"]
    lines += [f"\t{n} = \"rbxassetid://{v['id']}\"," for n, v in sorted(lock.items())]
    open(LUA, "w").write("\n".join(lines + ["}", ""]))


if __name__ == "__main__":
    main()
