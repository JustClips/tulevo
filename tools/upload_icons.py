"""Upload icon PNGs to Roblox as Images and write a Luau table of their asset ids.

  python3 tools/upload_icons.py [--set icons|items] [--force]

  icons (default): art/icons/out/*.png -> src/shared/IconIds.luau
                   (UI icons from art/icons/gen.py (ForgeGUI) + proc.py)
  items:           art/items/out/*.png -> src/shared/ItemIconIds.luau
                   (inventory item pictures from tools/item_icons/render.js)
  phone:           art/phone/out/*.png -> src/client/Phone/PhoneArt.luau
                   (phone body + wallpaper from art/phone/gen.py + proc.py; adds out/meta.json)
  phone_apps:      art/phone/apps/*.png -> src/client/Phone/AppIcons.luau (art/phone/gen_apps.py)

Needs env ROBLOXAPIKEY (never printed). Unchanged files are skipped (hash cache in
art/<set>.lock.json).
"""
import hashlib
import json
import os
import sys
import time
import uuid

sys.path.insert(0, os.path.dirname(__file__))
from upload_anims import CREATOR, request  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SETS = {  # set: (Luau file under src, label, folder with the PNGs under art)
    "icons": ("shared/IconIds", "UI icon", "icons/out"),
    "items": ("shared/ItemIconIds", "item icon", "items/out"),
    "phone": ("client/Phone/PhoneArt", "phone art", "phone/out"),
    "phone_apps": ("client/Phone/AppIcons", "phone app icon", "phone/apps"),
}
SET = sys.argv[sys.argv.index("--set") + 1] if "--set" in sys.argv else "icons"
MODULE, LABEL, FOLDER = SETS[SET]
SRC = os.path.join(ROOT, "art", *FOLDER.split("/"))
LOCK = os.path.join(ROOT, "art", f"{SET}.lock.json")
LUA = os.path.join(ROOT, "src", *f"{MODULE}.luau".split("/"))


def upload(path, name):
    meta = {"assetType": "Image", "displayName": f"Tulevo {LABEL} {name}"[:50], "description": f"Tulevo {LABEL}: {name}",
            "creationContext": {"creator": {"userId": CREATOR}}}
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n"
            f"{json.dumps(meta)}\r\n--{b}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{os.path.basename(path)}\"\r\nContent-Type: image/png\r\n\r\n").encode() + open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    code, op = request("POST", "https://apis.roblox.com/assets/v1/assets", body, {"Content-Type": f"multipart/form-data; boundary={b}"})
    if code >= 300:
        raise RuntimeError(f"upload {name} failed: {code} {op}")
    for _ in range(150):
        if op.get("done"):
            break
        time.sleep(2)
        code, op = request("GET", f"https://apis.roblox.com/assets/v1/{op['path']}")
    if not op.get("done"):
        raise RuntimeError(f"upload {name} timed out: {op}")
    asset_id = int((op.get("response") or {})["assetId"])
    body = {"subjectType": "All", "action": "Use", "requests": [{"assetId": asset_id, "grantToDependencies": False}]}
    code, r = request("PATCH", "https://apis.roblox.com/asset-permissions-api/v1/assets/permissions",
                      json.dumps(body).encode(), {"Content-Type": "application/json-patch+json"})
    if code >= 300:
        print(f"  grant All for {name}: {code} {r}")
    return asset_id


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    for f in sorted(os.listdir(SRC)):
        if not f.endswith(".png"):
            continue
        name = f[:-4]
        path = os.path.join(SRC, f)
        h = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if lock.get(name, {}).get("sha") == h and "--force" not in sys.argv:
            continue
        print(f"uploading {name} ...")
        lock[name] = {"id": upload(path, name), "sha": h}
        print(f"  {name} = {lock[name]['id']}")
        json.dump(lock, open(LOCK, "w"), indent=1)
    lines = [f"-- Generated by tools/upload_icons.py. Roblox Image asset ids for art/{SET}/out/*.png.", "return {"]
    lines += [f"\t{n} = \"rbxassetid://{v['id']}\"," for n, v in sorted(lock.items())]
    meta = os.path.join(SRC, "meta.json")
    if os.path.exists(meta):  # extra plain values (numbers / lists of numbers) from the art script
        for n, v in sorted(json.load(open(meta)).items()):
            lines.append(f"\t{n} = {{ {', '.join(str(x) for x in v)} }}," if isinstance(v, list) else f"\t{n} = {v},")
    open(LUA, "w").write("\n".join(lines + ["}", ""]))


if __name__ == "__main__":
    main()
