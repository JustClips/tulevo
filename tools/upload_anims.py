"""Upload art/out/anims/*.rbxmx to Roblox as Animations and write src/shared/AnimIds.luau.

  python3 art/anim/locomotion.py && python3 tools/upload_anims.py

Needs env ROBLOXAPIKEY (Open Cloud key with asset write for Dev's account 822623546; never
printed). Unchanged files are skipped (hash cache in art/anims.lock.json). Each new upload is
granted Use to Dev's alt account and group so Studio play-tests on either account can load it.
"""
import hashlib
import json
import os
import ssl
import sys
import time
import urllib.error
import urllib.request
import uuid

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "art", "out", "anims")
LOCK = os.path.join(ROOT, "art", "anims.lock.json")
LUA = os.path.join(ROOT, "src", "shared", "AnimIds.luau")
CREATOR = "822623546"
GRANTS = [("User", "347852675"), ("Group", "351097046")]
CTX = ssl.create_default_context(cafile="/root/.ccr/ca-bundle.crt") if os.path.exists("/root/.ccr/ca-bundle.crt") else ssl.create_default_context()


def request(method, url, body=None, headers=None):
    h = {"x-api-key": os.environ["ROBLOXAPIKEY"]}
    h.update(headers or {})
    r = urllib.request.Request(url, data=body, method=method, headers=h)
    try:
        with urllib.request.urlopen(r, context=CTX, timeout=180) as resp:
            data = resp.read()
            return resp.status, json.loads(data) if data else {}
    except urllib.error.HTTPError as e:
        data = e.read().decode(errors="replace")
        try:
            return e.code, json.loads(data)
        except Exception:
            return e.code, {"raw": data[:500]}


def upload(path, name):
    meta = {"assetType": "Animation", "displayName": name[:50], "description": f"Tulevo: {name}",
            "creationContext": {"creator": {"userId": CREATOR}}}
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n"
            f"{json.dumps(meta)}\r\n--{b}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{os.path.basename(path)}\"\r\nContent-Type: model/x-rbxm\r\n\r\n").encode() + open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    code, op = request("POST", "https://apis.roblox.com/assets/v1/assets", body, {"Content-Type": f"multipart/form-data; boundary={b}"})
    if code >= 300:
        raise RuntimeError(f"upload {name} failed: {code} {op}")
    for _ in range(90):
        if op.get("done"):
            break
        time.sleep(2)
        code, op = request("GET", f"https://apis.roblox.com/assets/v1/{op['path']}")
    asset_id = int((op.get("response") or {})["assetId"])
    for subject, sid in GRANTS:
        for attempt in range(6):
            body = {"subjectType": subject, "subjectId": sid, "action": "Use", "requests": [{"assetId": asset_id, "grantToDependencies": False}]}
            code, r = request("PATCH", "https://apis.roblox.com/asset-permissions-api/v1/assets/permissions",
                              json.dumps(body).encode(), {"Content-Type": "application/json-patch+json"})
            errs = (r.get("errors") if isinstance(r, dict) else None) or []
            if code < 300 and not errs:
                break
            print(f"  grant {subject} {sid}: {code} {errs or r}")
            time.sleep(10)
    return asset_id


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith(".rbxmx"):
            continue
        name = fn[:-6]
        h = hashlib.sha256(open(os.path.join(SRC, fn), "rb").read()).hexdigest()
        if lock.get(name, {}).get("sha") == h and "--force" not in sys.argv:
            continue
        lock[name] = {"id": upload(os.path.join(SRC, fn), name), "sha": h}
        print("uploaded", name, lock[name]["id"])
        json.dump(lock, open(LOCK, "w"), indent=1, sort_keys=True)
    lines = ["-- Generated by tools/upload_anims.py. Animation ids by name.", "return {"]
    lines += [f'\t{k} = "rbxassetid://{v["id"]}",' for k, v in sorted(lock.items())]
    lines.append("}")
    open(LUA, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
