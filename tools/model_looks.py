"""Write src/shared/ModelLooks.luau: the Roblox look (Color / Material / Reflectance / Transparency) of every
part, from the "looks" table in art/models/<Model>/meta.json (the superbike part scripts write these).

  python3 tools/model_looks.py        (tools/upload_models.py also runs it)

Server/Showcase paints MeshParts from this, so a new model needs no hand-written looks table.
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "art", "models")
LUA = os.path.join(ROOT, "src", "shared", "ModelLooks.luau")


def look_lua(part, look):
    """One table entry, laid out the way StyLua wants it (one line if it fits in 120 columns, tab = 4)."""
    r, g, b = look["Color"]
    out = [f"Color = Color3.fromRGB({r}, {g}, {b})", f"Material = Enum.Material.{look['Material']}"]
    for key in ("Reflectance", "Transparency"):
        if look.get(key):
            out.append(f"{key} = {round(float(look[key]), 3)}")
    line = f"\t\t{part} = {{ " + ", ".join(out) + " },"
    if len(line.expandtabs(4)) <= 120:
        return [line]
    return [f"\t\t{part} = {{"] + [f"\t\t\t{o}," for o in out] + ["\t\t},"]


def main():
    lines = ["-- Generated by tools/model_looks.py from art/models/*/meta.json: part name -> look, per model.", "return {"]
    for name in sorted(os.listdir(SRC)):
        meta_p = os.path.join(SRC, name, "meta.json")
        if not os.path.exists(meta_p):
            continue
        looks = json.load(open(meta_p)).get("looks")
        if not looks:
            continue
        lines.append(f"\t{name} = {{")
        for part, look in looks.items():
            lines += look_lua(part, look)
        lines.append("\t},")
    open(LUA, "w").write("\n".join(lines + ["}", ""]))


if __name__ == "__main__":
    main()
