"""Street lamps as Roblox "City Prop - Lamp" models instead of baked meshes (2026-11-07).

  python3 tools/city_props.py && python3 tools/city_colliders.py StreetVaultAvenue StreetBackStreet \
      StreetNorthStreet StreetSouthStreet StreetWestStreet StreetEastStreet

- writes src/server/CityPropLayout.luau: every "Light" spot from art/blender/cityfill/street_layout.json
  (Roblox position on the sidewalk + the direction toward the road), grouped by street model
  and every "Signal" spot of StreetCorners (key Signals)
- drops the old lamp pole collider boxes (the non-concrete box on each lamp spot) from
  art/models/Street*/meta.json, so no invisible poles stay behind. The concrete plinth box stays.
Safe to run again.
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
LAYOUT = os.path.join(ROOT, "art", "blender", "cityfill", "street_layout.json")
OUT = os.path.join(ROOT, "src", "server", "CityPropLayout.luau")


def main():
    layout = json.load(open(LAYOUT))
    lines = ["-- Generated by tools/city_props.py from art/blender/cityfill/street_layout.json.",
             "-- Street lamp spots: { x, y, z, hx, hz } = Roblox sidewalk point + unit direction to the road.",
             "return {"]
    total = dropped = 0
    for model, props in layout.items():
        lights = [p for p in props if p.get("kind") == "Light"]
        if not lights:
            continue
        lines.append(f"\t{model} = {{")
        for p in lights:
            lines.append(f"\t\t{{ {p['x']}, {p['y']}, {p['z']}, {p['hx']}, {p['hz']} }},")
        lines.append("\t},")
        total += len(lights)
        meta_p = os.path.join(ROOT, "art", "models", model, "meta.json")
        meta = json.load(open(meta_p))
        spots = {(round(-p["x"], 2), round(p["z"], 2)) for p in lights}   # Blender (x, y) = Roblox (-x, z)
        keep = []
        for b in meta.get("collider_boxes", []):
            if (round(b[0], 2), round(b[1], 2)) in spots and b[7] != "Concrete":
                dropped += 1
                continue
            keep.append(b)
        meta["collider_boxes"] = keep
        json.dump(meta, open(meta_p, "w"), indent=1)
    # traffic signals (StreetCorners): { x, y, z, dx, dz, arm, phase } = plinth point, direction of
    # the traffic the heads face, arm length over its lanes, signal phase EW/NS
    sigs = [p for p in layout.get("StreetCorners", []) if p.get("kind") == "Signal"]
    lines.append("\tSignals = {")
    for p in sigs:
        lines.append(f"\t\t{{ {p['x']}, {p['y']}, {p['z']}, {p['dx']}, {p['dz']}, {p['arm']}, \"{p['phase']}\" }},")
    lines.append("\t},")
    lines.append("}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"{total} lamp spots + {len(sigs)} signals -> {os.path.relpath(OUT, ROOT)}, dropped {dropped} pole colliders")


if __name__ == "__main__":
    main()
